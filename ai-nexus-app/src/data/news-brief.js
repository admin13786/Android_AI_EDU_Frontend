const normalizeIssue = (issue) => ({
  ...issue,
  items: Array.isArray(issue.items) ? issue.items : [],
})

export const getNewsBriefIssues = () => MOCK_ISSUES.map((issue) => normalizeIssue(issue))

export const getLatestNewsBriefIssue = () => normalizeIssue(MOCK_ISSUES[0])

export const getRecentNewsBriefIssues = (limit = 7) =>
  MOCK_ISSUES.slice(0, limit).map((issue) => normalizeIssue(issue))

export const getNewsBriefIssueById = (id) =>
  normalizeIssue(MOCK_ISSUES.find((issue) => issue.id === id) || MOCK_ISSUES[0])

export const getNewsBriefItemsByIssueId = (issueId) => getNewsBriefIssueById(issueId).items

export const getNewsBriefItemByIds = (issueId, itemId) => {
  const issue = getNewsBriefIssueById(issueId)
  return issue.items.find((item) => item.id === itemId) || issue.items[0] || null
}
